import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import {
  DISCOVERY_TRAILS,
  EDGES,
  NODES,
  PUBLISHED_EDGES,
  PUBLISHED_NODES
} from '../src/data.js';
import {
  buildRuntimeGraphSnapshot,
  buildRuntimeNodeDetails
} from '../src/runtime-data-projection.js';

const outputUrl = new URL('../src/runtime-graph.generated.js', import.meta.url);
const nodeDetailsUrl = new URL('../public/runtime-node-details.json', import.meta.url);
const snapshot = buildRuntimeGraphSnapshot({
  nodes: NODES,
  edges: EDGES,
  publishedNodes: PUBLISHED_NODES,
  publishedEdges: PUBLISHED_EDGES,
  discoveryTrails: DISCOVERY_TRAILS
});
const source = `/* This file is generated by scripts/export-runtime-graph.mjs. */\nexport default ${JSON.stringify(snapshot)};\n`;
const nodeDetailsSource = JSON.stringify({
  version: 1,
  nodes: buildRuntimeNodeDetails(NODES)
});

await writeFile(outputUrl, source, 'utf8');
await writeFile(nodeDetailsUrl, nodeDetailsSource, 'utf8');

console.log(`Runtime graph written to ${fileURLToPath(outputUrl)} (${Buffer.byteLength(source).toLocaleString('en-US')} bytes).`);
console.log(`Runtime node details written to ${fileURLToPath(nodeDetailsUrl)} (${Buffer.byteLength(nodeDetailsSource).toLocaleString('en-US')} bytes).`);
